"""Viral V. Acharya, Lasse Heje Pedersen, Thomas Philippon & Matthew Richardson (2017)
Systemic Expected Shortfall (SES), Marginal Expected Shortfall (MES) & Capital Surcharge Engine.

Implements the Systemic Risk Measurement framework:
- Acharya, Pedersen, Philippon & Richardson (2017, Review of Financial Studies, "Measuring Systemic Risk"):
    Systemic risk is the risk that many market participants face simultaneous liquidity or capital shortfalls,
    imposing aggregate negative externalities on the real economy.
    - Marginal Expected Shortfall (MES_i): An individual firm's or stock's expected percentage loss conditional
      on the aggregate financial system suffering a severe tail event (market return R_m <= -C, e.g., C = 2.0% daily):
          MES_i = -E[R_i | R_m <= -C]
    - Systemic Expected Shortfall (SES_i): An institution's or asset's expected contribution to an aggregate
      capital shortfall in a systemic crisis. SES is linearly determined by initial leverage (Lev_i = Assets / Equity)
      and marginal tail risk sensitivity (MES_i):
          SES_i = alpha_0 + alpha_1 * MES_i + alpha_2 * Lev_i
    - Pigouvian Systemic Capital Surcharge (tau_i): The regulatory capital buffer or insurance premium needed to
      internalize the systemic externality generated by the asset's tail loss and leverage.

- Acharya, Engle & Richardson (2012, Critical Finance Review):
    Dynamic systemic risk quantification linking cross-sectional volatility, leverage, and correlation
    to systemic equity shortfall.

References:
    Acharya, V. V., Pedersen, L. H., Philippon, T., & Richardson, M. (2017). Measuring systemic risk.
    The Review of Financial Studies, 30(1), 2-47.
    Acharya, V. V., Engle, R., & Richardson, M. (2012). Capital shortfall: A new approach to ranking
    and regulating systemic risks. The American Economic Review, 102(3), 59-64.
"""

from __future__ import annotations

from dataclasses import asdict, dataclass, field
from datetime import datetime, timezone
import hashlib
import hmac
import math
from pathlib import Path
from typing import Any, Dict, Optional, Union

import numpy as np

import src.data.db as db
from src.security.validators import assert_finite_number, validate_ticker

SES_SIGNING_KEY = b"nextomni_systemic_expected_shortfall_v1"


@dataclass
class SystemicExpectedShortfallReceipt:
    """Cryptographic audit receipt for Acharya et al. (2017) Systemic Expected Shortfall Profile."""

    ticker: str
    latest_price: float
    # Systemic Conditioning & Tail Parameters
    market_tail_threshold_pct: float  # Conditioning crisis drop C (%) in [1.0, 15.0]
    marginal_expected_shortfall_pct: float  # MES_i = -E[R_i | R_m <= -C] (%) in [-5.0, 30.0]
    institution_leverage: float  # Leverage Assets / Equity in [1.0, 45.0]
    baseline_leverage: float  # Normal-times leverage in [1.0, 25.0]
    # Derived Systemic Risk Metrics
    systemic_expected_shortfall_pct: float  # SES_i in [-5.0, 35.0] (%)
    systemic_capital_surcharge_pct: float  # Pigouvian externality tax tau_i in [0.0, 10.0] (%)
    tail_dependence_ratio: float  # MES_i / C in [0.10, 5.0]
    systemic_fragility_impulse: float  # I_ses in [-2.5, 2.5]
    expected_systemic_alpha_pct: float  # Projected annualized alpha net of systemic risk tax (%)
    # Flags & Regime
    is_critical_systemic_threat: bool  # True if MES >= 4.5% and Lev >= 15.0 and SES >= 6.0%
    is_defensive_systemic_resilience: bool  # True if MES <= 1.2% and Lev <= 5.0 (safe haven)
    is_elevated_tail_sensitivity: bool  # True if MES >= 3.0%
    regime: str
    summary: str
    created_at_utc: str = field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat()
    )
    signature: str = ""

    def __post_init__(self) -> None:
        if not self.signature:
            self.signature = self._compute_signature()

    def _compute_signature(self) -> str:
        """Compute deterministic HMAC-SHA256 signature across all systemic risk metrics."""
        payload = (
            f"{self.ticker}:{self.latest_price:.2f}:"
            f"{self.market_tail_threshold_pct:.4f}:{self.marginal_expected_shortfall_pct:.4f}:"
            f"{self.institution_leverage:.4f}:{self.baseline_leverage:.4f}:"
            f"{self.systemic_expected_shortfall_pct:.4f}:{self.systemic_capital_surcharge_pct:.4f}:"
            f"{self.tail_dependence_ratio:.4f}:{self.systemic_fragility_impulse:.4f}:"
            f"{self.expected_systemic_alpha_pct:.2f}:"
            f"{int(self.is_critical_systemic_threat)}:{int(self.is_defensive_systemic_resilience)}:{int(self.is_elevated_tail_sensitivity)}:{self.regime}"
        )
        return hmac.new(
            SES_SIGNING_KEY,
            payload.encode("utf-8"),
            hashlib.sha256,
        ).hexdigest()

    def verify_integrity(self) -> bool:
        """Verify receipt authenticity and cryptographic tamper resistance."""
        expected = self._compute_signature()
        return hmac.compare_digest(self.signature, expected)

    def to_dict(self) -> Dict[str, Any]:
        """Convert receipt to dictionary format for JSON serialization."""
        return asdict(self)


def classify_systemic_risk_regime(
    marginal_expected_shortfall: float,
    institution_leverage: float,
    systemic_expected_shortfall: float,
) -> str:
    """Classify asset into Acharya et al. (2017) Systemic Risk Regimes."""
    if (
        marginal_expected_shortfall >= 4.5
        and institution_leverage >= 15.0
        and systemic_expected_shortfall >= 6.0
    ):
        return "CRITICAL_SYSTEMIC_EXTERNALITY_THREAT"
    if marginal_expected_shortfall <= 1.2 and institution_leverage <= 6.0:
        return "DEFENSIVE_SYSTEMIC_RESILIENCE"
    if marginal_expected_shortfall >= 3.0:
        return "ELEVATED_MARGINAL_TAIL_SENSITIVITY"
    return "NORMAL_SYSTEMIC_CAPITAL_EQUILIBRIUM"


def calculate_systemic_expected_shortfall(
    ticker: str,
    latest_price: float,
    market_tail_threshold_pct: float = 2.00,
    marginal_expected_shortfall_pct: float = 3.20,
    institution_leverage: float = 12.0,
    baseline_leverage: float = 10.0,
) -> SystemicExpectedShortfallReceipt:
    """Calculate Acharya et al. (2017) Systemic Expected Shortfall & Capital Surcharge.

    Args:
        ticker: Validated stock ticker symbol.
        latest_price: Latest closing stock price P_t ($ > 0).
        market_tail_threshold_pct: Crisis market drop threshold C (%) in [1.0, 15.0].
        marginal_expected_shortfall_pct: MES_i = -E[R_i | R_m <= -C] (%) in [-5.0, 30.0].
        institution_leverage: Leverage ratio Assets / Equity in [1.0, 45.0].
        baseline_leverage: Baseline regulatory leverage in [1.0, 25.0].

    Returns:
        SystemicExpectedShortfallReceipt with SES, surcharge tau_i, impulse, and regime.
    """
    clean_ticker = validate_ticker(ticker)
    assert_finite_number(latest_price, "latest_price")
    assert_finite_number(market_tail_threshold_pct, "market_tail_threshold_pct")
    assert_finite_number(marginal_expected_shortfall_pct, "marginal_expected_shortfall_pct")
    assert_finite_number(institution_leverage, "institution_leverage")
    assert_finite_number(baseline_leverage, "baseline_leverage")

    if latest_price <= 0.0:
        raise ValueError("latest_price must be strictly positive.")
    if not (1.0 <= market_tail_threshold_pct <= 15.0):
        raise ValueError("market_tail_threshold_pct must be in [1.0, 15.0].")
    if not (-5.0 <= marginal_expected_shortfall_pct <= 30.0):
        raise ValueError("marginal_expected_shortfall_pct must be in [-5.0, 30.0].")
    if not (1.0 <= institution_leverage <= 45.0):
        raise ValueError("institution_leverage must be in [1.0, 45.0].")
    if not (1.0 <= baseline_leverage <= 25.0):
        raise ValueError("baseline_leverage must be in [1.0, 25.0].")

    p_t = float(latest_price)
    c_tail = float(market_tail_threshold_pct)
    mes = float(marginal_expected_shortfall_pct)
    lev = float(institution_leverage)
    lev_0 = float(baseline_leverage)

    # 1. Acharya et al. (2017) Systemic Expected Shortfall (SES_i)
    # Calibrated linear relation: SES = -0.15 + 0.85 * MES + 0.28 * max(0, Lev - 5.0)
    ses_raw = -0.15 + 0.85 * mes + 0.28 * max(0.0, lev - 5.0)
    ses = float(np.clip(ses_raw, -5.0, 35.0))

    # 2. Tail Dependence Ratio (MES / C)
    tail_ratio = float(np.clip(mes / max(c_tail, 0.5), 0.10, 5.0))

    # 3. Pigouvian Systemic Capital Surcharge (tau_i)
    # Higher SES combined with excessive leverage above normal-times baseline incurs systemic externality tax
    excess_lev = max(0.0, (lev - lev_0) / max(lev_0, 1.0))
    tau_raw = 0.04 * max(0.0, ses) + 1.25 * excess_lev
    tau = float(np.clip(tau_raw, 0.0, 10.0))

    # 4. Systemic Fragility Impulse & Expected Alpha
    # High SES imposes capital drag and vulnerability, producing negative alpha
    # Low MES/SES assets benefit from systemic flight-to-safety resilience
    raw_impulse = -0.35 * (ses / 5.0) - 0.25 * excess_lev + 0.30 * max(0.0, 1.5 - tail_ratio)
    impulse = float(np.clip(raw_impulse, -2.5, 2.5))
    expected_alpha = float(np.clip(3.5 * impulse, -12.0, 10.0))

    regime = classify_systemic_risk_regime(mes, lev, ses)
    is_critical = bool(regime == "CRITICAL_SYSTEMIC_EXTERNALITY_THREAT")
    is_defensive = bool(regime == "DEFENSIVE_SYSTEMIC_RESILIENCE")
    is_elevated = bool(regime == "ELEVATED_MARGINAL_TAIL_SENSITIVITY")

    if regime == "CRITICAL_SYSTEMIC_EXTERNALITY_THREAT":
        summary = (
            f"Critical Systemic Externality Threat (MES={mes:.2f}%, Lev={lev:.1f}x, SES={ses:.2f}%, Surcharge={tau:.2f}%). "
            f"Severe tail conditional losses coupled with high leverage generate acute systemic crisis risk ({expected_alpha:+.1f}%/yr)."
        )
    elif regime == "DEFENSIVE_SYSTEMIC_RESILIENCE":
        summary = (
            f"Defensive Systemic Resilience (MES={mes:.2f}%, Lev={lev:.1f}x, SES={ses:.2f}%). "
            f"Minimal sensitivity to aggregate market crashes provides flight-to-safety protection and systemic resilience ({expected_alpha:+.1f}%/yr)."
        )
    elif regime == "ELEVATED_MARGINAL_TAIL_SENSITIVITY":
        summary = (
            f"Elevated Marginal Tail Sensitivity (MES={mes:.2f}%, Tail_Ratio={tail_ratio:.2f}x, SES={ses:.2f}%). "
            f"Stock experiences disproportionate losses during aggregate financial panic sessions ({expected_alpha:+.1f}%/yr)."
        )
    else:
        summary = (
            f"Normal Systemic Capital Equilibrium (MES={mes:.2f}%, Lev={lev:.1f}x, SES={ses:.2f}%). "
            f"Systemic tail risk exposure and leverage are comfortably within balanced prudential thresholds ({expected_alpha:+.1f}%/yr)."
        )

    return SystemicExpectedShortfallReceipt(
        ticker=clean_ticker,
        latest_price=round(p_t, 2),
        market_tail_threshold_pct=round(c_tail, 2),
        marginal_expected_shortfall_pct=round(mes, 2),
        institution_leverage=round(lev, 2),
        baseline_leverage=round(lev_0, 2),
        systemic_expected_shortfall_pct=round(ses, 2),
        systemic_capital_surcharge_pct=round(tau, 2),
        tail_dependence_ratio=round(tail_ratio, 2),
        systemic_fragility_impulse=round(impulse, 4),
        expected_systemic_alpha_pct=round(expected_alpha, 2),
        is_critical_systemic_threat=is_critical,
        is_defensive_systemic_resilience=is_defensive,
        is_elevated_tail_sensitivity=is_elevated,
        regime=regime,
        summary=summary,
    )


def evaluate_ses_profile(
    ticker: str,
    db_path: Optional[Union[str, Path]] = None,
    market_tail_threshold_pct: Optional[float] = None,
    marginal_expected_shortfall_pct: Optional[float] = None,
    institution_leverage: Optional[float] = None,
    baseline_leverage: Optional[float] = None,
) -> SystemicExpectedShortfallReceipt:
    """Evaluate Acharya et al. (2017) SES profile from SQLite OHLCV and overrides."""
    clean_ticker = validate_ticker(ticker)

    latest_price = 100.0
    inferred_c = 2.00
    inferred_mes = 3.20
    inferred_lev = 10.0
    inferred_lev0 = 10.0

    try:
        obs = db.get_observations(clean_ticker, db_path=db_path)
        if obs is not None and not obs.empty and "close" in obs.columns:
            closes = [
                float(x)
                for x in obs["close"].tolist()
                if math.isfinite(float(x)) and float(x) > 0
            ]
            if closes:
                latest_price = closes[-1]
            if len(closes) >= 20:
                arr = np.asarray(closes[-min(len(closes), 252) :], dtype=float)
                rets = np.diff(arr) / arr[:-1]

                # Estimate MES from empirical 5% worst left-tail session losses
                q5 = float(np.percentile(rets, 5.0))
                tail_losses = [-float(r) for r in rets if r <= q5]
                if tail_losses:
                    inferred_mes = float(np.clip(100.0 * np.mean(tail_losses), 0.5, 20.0))

                ann_vol = float(np.std(rets, ddof=1) * math.sqrt(252.0)) if len(rets) > 1 else 0.22
                inferred_lev = float(np.clip(5.0 + 25.0 * ann_vol, 3.0, 30.0))
    except Exception:
        latest_price = 100.0

    c_val = float(market_tail_threshold_pct) if market_tail_threshold_pct is not None else inferred_c
    mes_val = float(marginal_expected_shortfall_pct) if marginal_expected_shortfall_pct is not None else inferred_mes
    lev_val = float(institution_leverage) if institution_leverage is not None else inferred_lev
    lev0_val = float(baseline_leverage) if baseline_leverage is not None else inferred_lev0

    return calculate_systemic_expected_shortfall(
        ticker=clean_ticker,
        latest_price=latest_price,
        market_tail_threshold_pct=c_val,
        marginal_expected_shortfall_pct=mes_val,
        institution_leverage=lev_val,
        baseline_leverage=lev0_val,
    )

