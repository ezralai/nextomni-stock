"""Tobias Adrian & Markus K. Brunnermeier (2016)
CoVaR, Delta-CoVaR & Systemic Tail Spillover Contagion Engine.

Implements the Adrian & Brunnermeier CoVaR framework:
- Adrian & Brunnermeier (2016, American Economic Review, "CoVaR"):
    Value-at-Risk (VaR) measures individual risk in isolation, failing to capture systemic spillover externalities.
    CoVaR is the Value-at-Risk of the financial system conditional on institution or asset i being in distress:
        Pr(R_m <= CoVaR_{m|i}^q | R_i = VaR_i^q) = q
    The marginal systemic contribution (Delta-CoVaR_i) is the difference between the system's VaR when asset i
    is in distress vs. when asset i is in its median state:
        Delta-CoVaR_i^q = CoVaR_{m|i}^q - CoVaR_{m|Median_i}^q
    - Directional Tail Spillover: Quantifies systemic contagion generated by an institution/asset.
    - Systemic Exposure CoVaR (Delta-CoVaR_{i|m}^q): Quantifies how severely asset i is impacted when the
      entire financial system is in crisis.

References:
    Adrian, T., & Brunnermeier, M. K. (2016). CoVaR.
    American Economic Review, 106(7), 1705-1741.
"""

from __future__ import annotations

from dataclasses import asdict, dataclass, field
from datetime import datetime, timezone
import hashlib
import hmac
import math
