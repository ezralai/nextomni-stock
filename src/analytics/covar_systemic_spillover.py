COVAR_SIGNING_KEY = b"nextomni_covar_systemic_spillover_v1"


@dataclass
class CoVaRSpilloverReceipt:
    """Cryptographic audit receipt for Adrian-Brunnermeier (2016) CoVaR & Delta-CoVaR."""

    ticker: str
    latest_price: float
    # Tail & Quantile Conditioning Inputs
    tail_quantile: float  # Quantile q (e.g. 0.05 for 95% VaR) in [0.01, 0.15]
    standalone_var_pct: float  # Individual VaR_i^q (%) in [1.0, 30.0]
    system_unconditional_var_pct: float  # Unconditional system VaR_m^q (%) in [1.0, 20.0]
    tail_beta: float  # Quantile regression slope beta_{m|i}^q in [0.0, 3.5]
    # Derived CoVaR & Spillover Metrics
    conditional_system_covar_pct: float  # CoVaR_{m|i}^q (%) in [1.0, 35.0]
    delta_covar_pct: float  # Delta-CoVaR_i^q = CoVaR_{m|i} - CoVaR_{m|median} (%) in [-1.0, 18.0]
    systemic_exposure_covar_pct: float  # Delta-CoVaR_{i|m}^q (%) in [-1.0, 25.0]
    systemic_spillover_multiplier: float  # Delta-CoVaR / system_unconditional_var in [0.0, 4.0]
    covar_fragility_impulse: float  # I_covar in [-2.5, 2.5]
    expected_covar_alpha_pct: float  # Projected annualized alpha net of spillover externality (%)
    # Flags & Regime
    is_critical_spillover_threat: bool  # True if Delta-CoVaR >= 3.5% and tail_beta >= 1.2
    is_systemic_distress_absorber: bool  # True if Delta-CoVaR <= 0.8% and tail_beta <= 0.45
    is_elevated_spillover: bool  # True if Delta-CoVaR >= 1.8%
    regime: str
    summary: str
    created_at_utc: str = field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat()
    )
    signature: str = ""

    def __post_init__(self) -> None:
        if not self.signature:
            self.signature = self._compute_signature()

    def _compute_signature(self) -> str:
        """Compute deterministic HMAC-SHA256 signature across all CoVaR spillover metrics."""
        payload = (
            f"{self.ticker}:{self.latest_price:.2f}:"
            f"{self.tail_quantile:.4f}:{self.standalone_var_pct:.4f}:"
            f"{self.system_unconditional_var_pct:.4f}:{self.tail_beta:.4f}:"
            f"{self.conditional_system_covar_pct:.4f}:{self.delta_covar_pct:.4f}:"
            f"{self.systemic_exposure_covar_pct:.4f}:{self.systemic_spillover_multiplier:.4f}:"
            f"{self.covar_fragility_impulse:.4f}:{self.expected_covar_alpha_pct:.2f}:"
            f"{int(self.is_critical_spillover_threat)}:{int(self.is_systemic_distress_absorber)}:{int(self.is_elevated_spillover)}:{self.regime}"
        )
        return hmac.new(
            COVAR_SIGNING_KEY,
            payload.encode("utf-8"),
            hashlib.sha256,
        ).hexdigest()

    def verify_integrity(self) -> bool:
        """Verify receipt authenticity and cryptographic tamper resistance."""
        expected = self._compute_signature()
        return hmac.compare_digest(self.signature, expected)

    def to_dict(self) -> Dict[str, Any]:
        """Convert receipt to dictionary format for JSON serialization."""
        return asdict(self)


def classify_covar_regime(
    delta_covar: float,
    tail_beta: float,
    systemic_exposure: float,
) -> str:
    """Classify asset into Adrian & Brunnermeier (2016) CoVaR Regimes."""
    if delta_covar >= 3.50 and tail_beta >= 1.20:
        return "HIGH_SYSTEMIC_SPILLOVER_CONTAGION"
    if delta_covar <= 0.80 and tail_beta <= 0.45:
        return "SYSTEMIC_DISTRESS_ABSORBER"
    if delta_covar >= 1.80:
        return "ELEVATED_TAIL_SPILLOVER"
    return "NORMAL_TAIL_COVAR_EQUILIBRIUM"


def calculate_covar_spillover(
    ticker: str,
    latest_price: float,
    tail_quantile: float = 0.05,
    standalone_var_pct: float = 3.80,
    system_unconditional_var_pct: float = 2.40,
    tail_beta: float = 1.10,
) -> CoVaRSpilloverReceipt:
    """Calculate Adrian & Brunnermeier (2016) CoVaR and Delta-CoVaR metrics.

    Args:
        ticker: Validated stock ticker symbol.
        latest_price: Latest closing stock price P_t ($ > 0).
        tail_quantile: Tail probability q in [0.01, 0.15] (default 0.05).
        standalone_var_pct: Stock's standalone VaR_i^q (%) in [1.0, 30.0].
        system_unconditional_var_pct: System market VaR_m^q (%) in [1.0, 20.0].
        tail_beta: Tail regression slope beta_{m|i}^q in [0.0, 3.5].

    Returns:
        CoVaRSpilloverReceipt with CoVaR, Delta-CoVaR, spillover multiplier, and regime.
    """
    clean_ticker = validate_ticker(ticker)
    assert_finite_number(latest_price, "latest_price")
    assert_finite_number(tail_quantile, "tail_quantile")
    assert_finite_number(standalone_var_pct, "standalone_var_pct")
    assert_finite_number(system_unconditional_var_pct, "system_unconditional_var_pct")
    assert_finite_number(tail_beta, "tail_beta")

    if latest_price <= 0.0:
        raise ValueError("latest_price must be strictly positive.")
    if not (0.01 <= tail_quantile <= 0.15):
        raise ValueError("tail_quantile must be in [0.01, 0.15].")
    if not (1.0 <= standalone_var_pct <= 30.0):
        raise ValueError("standalone_var_pct must be in [1.0, 30.0].")
    if not (1.0 <= system_unconditional_var_pct <= 20.0):
        raise ValueError("system_unconditional_var_pct must be in [1.0, 20.0].")
    if not (0.0 <= tail_beta <= 3.5):
        raise ValueError("tail_beta must be in [0.0, 3.5].")

    p_t = float(latest_price)
    q = float(tail_quantile)
    var_i = float(standalone_var_pct)
    var_m = float(system_unconditional_var_pct)
    beta_tail = float(tail_beta)

    # 1. Adrian-Brunnermeier Conditional System CoVaR:
    # CoVaR_{m|i}^q = gamma_0 + beta_{m|i}^q * VaR_i^q
    # When median state has near-zero excess loss, Delta-CoVaR = beta_{m|i}^q * (VaR_i^q - Median_i)
    # Calibrated baseline intercept gamma_0 reflects system core risk:
    gamma_0 = 0.65 * var_m
    covar_m = float(np.clip(gamma_0 + 0.55 * beta_tail * var_i, 1.0, 35.0))
    covar_median = float(np.clip(gamma_0 + 0.10 * beta_tail * (0.25 * var_i), 0.5, 20.0))
    delta_covar = float(np.clip(covar_m - covar_median, -1.0, 18.0))

    # 2. Systemic Exposure CoVaR (Delta-CoVaR_{i|m}^q)
    # Sensitivity of individual asset to system distress:
    exp_covar = float(np.clip(0.85 * beta_tail * var_m, -1.0, 25.0))

    # 3. Systemic Spillover Multiplier (Delta-CoVaR / var_m)
    spillover_mult = float(np.clip(delta_covar / max(var_m, 0.5), 0.0, 4.0))

    # 4. Fragility Impulse & Expected Alpha
    # High spillover externality creates regulatory/systemic tail drag; absorbers offer flight-to-safety resilience
    raw_impulse = -0.40 * (delta_covar / 3.0) + 0.35 * max(0.0, 1.2 - spillover_mult) - 0.25 * max(0.0, beta_tail - 1.2)
    impulse = float(np.clip(raw_impulse, -2.5, 2.5))
    expected_alpha = float(np.clip(3.4 * impulse, -12.0, 10.0))

    regime = classify_covar_regime(delta_covar, beta_tail, exp_covar)
    is_critical = bool(regime == "HIGH_SYSTEMIC_SPILLOVER_CONTAGION")
    is_absorber = bool(regime == "SYSTEMIC_DISTRESS_ABSORBER")
    is_elevated = bool(regime == "ELEVATED_TAIL_SPILLOVER")

    if regime == "HIGH_SYSTEMIC_SPILLOVER_CONTAGION":
        summary = (
            f"High Systemic Spillover Contagion (Delta-CoVaR={delta_covar:.2f}%, tail_beta={beta_tail:.2f}, Spillover={spillover_mult:.2f}x). "
            f"Asset distress triggers severe market-wide negative tail spillovers ({expected_alpha:+.1f}%/yr)."
        )
    elif regime == "SYSTEMIC_DISTRESS_ABSORBER":
        summary = (
            f"Systemic Distress Absorber (Delta-CoVaR={delta_covar:.2f}%, tail_beta={beta_tail:.2f}). "
            f"Asset is largely insulated from systemic contagion feedback and serves as distress buffer ({expected_alpha:+.1f}%/yr)."
        )
    elif regime == "ELEVATED_TAIL_SPILLOVER":
        summary = (
            f"Elevated Tail Spillover (Delta-CoVaR={delta_covar:.2f}%, CoVaR={covar_m:.2f}%, Spillover={spillover_mult:.2f}x). "
            f"Moderate tail loss propagation to aggregate financial system ({expected_alpha:+.1f}%/yr)."
        )
    else:
        summary = (
            f"Normal Tail CoVaR Equilibrium (Delta-CoVaR={delta_covar:.2f}%, VaR_i={var_i:.2f}%, CoVaR={covar_m:.2f}%). "
            f"Systemic spillover metrics are well within historical safety thresholds ({expected_alpha:+.1f}%/yr)."
        )

    return CoVaRSpilloverReceipt(
        ticker=clean_ticker,
        latest_price=round(p_t, 2),
        tail_quantile=round(q, 4),
        standalone_var_pct=round(var_i, 2),
        system_unconditional_var_pct=round(var_m, 2),
        tail_beta=round(beta_tail, 4),
        conditional_system_covar_pct=round(covar_m, 2),
        delta_covar_pct=round(delta_covar, 2),
        systemic_exposure_covar_pct=round(exp_covar, 2),
        systemic_spillover_multiplier=round(spillover_mult, 2),
        covar_fragility_impulse=round(impulse, 4),
        expected_covar_alpha_pct=round(expected_alpha, 2),
        is_critical_spillover_threat=is_critical,
        is_systemic_distress_absorber=is_absorber,
        is_elevated_spillover=is_elevated,
        regime=regime,
        summary=summary,
    )


def evaluate_covar_profile(
    ticker: str,
    db_path: Optional[Union[str, Path]] = None,
    tail_quantile: Optional[float] = None,
    standalone_var_pct: Optional[float] = None,
    system_unconditional_var_pct: Optional[float] = None,
    tail_beta: Optional[float] = None,
) -> CoVaRSpilloverReceipt:
    """Evaluate Adrian-Brunnermeier CoVaR profile from SQLite OHLCV and overrides."""
    clean_ticker = validate_ticker(ticker)

    latest_price = 100.0
    inferred_q = 0.05
    inferred_var_i = 3.80
    inferred_var_m = 2.40
    inferred_tail_beta = 1.10

    try:
        obs = db.get_observations(clean_ticker, db_path=db_path)
        if obs is not None and not obs.empty and "close" in obs.columns:
            closes = [
                float(x)
                for x in obs["close"].tolist()
                if math.isfinite(float(x)) and float(x) > 0
            ]
            if closes:
                latest_price = closes[-1]
            if len(closes) >= 20:
                arr = np.asarray(closes[-min(len(closes), 252) :], dtype=float)
                rets = np.diff(arr) / arr[:-1]

                # Estimate 95% historical empirical VaR
                q_level = float(tail_quantile) if tail_quantile is not None else 0.05
                q_loss = -float(np.percentile(rets, 100.0 * q_level))
                inferred_var_i = float(np.clip(100.0 * q_loss, 1.2, 25.0))

                ann_vol = float(np.std(rets, ddof=1) * math.sqrt(252.0)) if len(rets) > 1 else 0.22
                inferred_tail_beta = float(np.clip(ann_vol / 0.20, 0.20, 2.80))
    except Exception:
        latest_price = 100.0

    q_val = float(tail_quantile) if tail_quantile is not None else inferred_q
    var_i_val = float(standalone_var_pct) if standalone_var_pct is not None else inferred_var_i
    var_m_val = float(system_unconditional_var_pct) if system_unconditional_var_pct is not None else inferred_var_m
    beta_val = float(tail_beta) if tail_beta is not None else inferred_tail_beta

    return calculate_covar_spillover(
        ticker=clean_ticker,
        latest_price=latest_price,
        tail_quantile=q_val,
        standalone_var_pct=var_i_val,
        system_unconditional_var_pct=var_m_val,
        tail_beta=beta_val,
    )

